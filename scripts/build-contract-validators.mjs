import fs from 'node:fs/promises';
import {Ajv2020} from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standalone from 'ajv/dist/standalone/index.js';
import {build} from 'esbuild';
import {getRegisteredContracts} from '../dist/core/certificate-contract.js';
await import('../dist/core/preview-transfer-contract.js');
await import('../dist/core/estimate-publication.js');
await import('../dist/remote/experience.js');
await import('../dist/web/public-result-runtime.js');
const schemas=getRegisteredContracts();
const ajv=new Ajv2020({strict:false,ownProperties:true,code:{source:true}});addFormats(ajv);
const names={};let index=0;
for(const [hash,schema] of schemas){const name='v'+index++;ajv.addSchema(schema,hash);names[name]=hash;}
const source=standalone(ajv,names)+'\nexports.contractValidators={'+Object.entries(names).map(([name,hash])=>JSON.stringify(hash)+':exports.'+name).join(',')+'};';
// Bundle AJV's small CJS runtime helpers into portable ESM; no require/eval at runtime.
const result=await build({stdin:{contents:source,resolveDir:process.cwd(),loader:'js'},bundle:true,write:false,format:'esm',platform:'neutral',minify:true});
// CJS entry becomes an ESM default object.
const code=result.outputFiles[0].text.replace(/export default ([^;]+);?\s*$/, 'const generated=$1; export const contractValidators=generated.contractValidators;');
if(!code.includes('export const contractValidators='))throw new Error('STANDALONE_EXPORT_MISSING');
await fs.mkdir('src/generated',{recursive:true});
const destination='src/generated/contract-validators.ts',output='// @ts-nocheck\n// Generated by scripts/build-contract-validators.mjs; do not edit.\n'+code;
if(process.argv.includes('--check')){if(await fs.readFile(destination,'utf8')!==output)throw new Error('STALE_CONTRACT_VALIDATORS');}
else await fs.writeFile(destination,output);
console.log(JSON.stringify({validators:schemas.size,generated_bytes:Buffer.byteLength(output),runtime_compilation:false}));
